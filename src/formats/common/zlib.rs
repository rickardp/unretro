    fn big() -> Vec<u8> {
        (0..200_000u32).map(|i| (i % 251) as u8).collect()
    }

    fn decode(stream: &[u8], len: usize) -> Result<Vec<u8>> {
        // Sentinel fill shows that a failed decode leaves `out` untouched.
        let mut out = vec![0xA5; len];
        match zlib_decode_exact(stream, &mut out) {
            Ok(()) => Ok(out),
            Err(err) => {
                assert!(out.iter().all(|&b| b == 0xA5), "output written on error");
                Err(err)
            }
        }
    }

    fn error(stream: &[u8], len: usize) -> String {
        decode(stream, len).unwrap_err().to_string()
    }

    // Recomputes FCHECK after a header edit.
    fn with_header(stream: &[u8], cmf: u8, flags: u8) -> Vec<u8> {
        let base = (u16::from(cmf) << 8) | u16::from(flags & 0xE0);
        let check = (31 - base % 31) % 31;
        let mut out = stream.to_vec();
        out[0] = cmf;
        out[1] = (flags & 0xE0) | check as u8;
        out
    }

    #[test]
    fn adler32_matches_python_values() {
        assert_eq!(adler32(b""), 1);
        assert_eq!(adler32(b"abc"), 0x024D_0127);
        assert_eq!(adler32(b"Wikipedia"), 0x11E6_0398);
        assert_eq!(adler32(TEXT), 0xFE23_2608);
        assert_eq!(adler32(&big()), 0x49A0_7BDA);
    }

    #[test]
    fn adler32_does_not_overflow_on_worst_case_runs() {
        let data = vec![0xFFu8; 3 * ADLER_RUN + 17];
        let (mut low, mut high) = (1u64, 0u64);
        for &byte in &data {
            low = (low + u64::from(byte)) % 65521;
            high = (high + low) % 65521;
        }
        assert_eq!(u64::from(adler32(&data)), (high << 16) | low);
    }

    #[test]
    fn decodes_streams() {
        for stream in [Z_TEXT, Z_TEXT_FAST, Z_STORED, Z_SMALL_WINDOW] {
            assert_eq!(decode(stream, TEXT.len()).unwrap(), TEXT);
        }
        assert_eq!(decode(Z_EMPTY, 0).unwrap(), b"");
        assert_eq!(decode(Z_BIG, 200_000).unwrap(), big());
    }

    #[test]
    fn ignores_bytes_after_checksum() {
        let mut stream = Z_TEXT.to_vec();
        stream.extend_from_slice(b"trailing");
        assert_eq!(decode(&stream, TEXT.len()).unwrap(), TEXT);
    }

    #[test]
    fn rejects_bad_headers() {
        let mut bad_check = Z_TEXT.to_vec();
        bad_check[1] ^= 1;
        assert!(error(&bad_check, TEXT.len()).contains("check bits"));

        let method = with_header(Z_TEXT, 0x77, Z_TEXT[1]);
        assert!(error(&method, TEXT.len()).contains("compression method 7"));

        let window = with_header(Z_TEXT, 0x88, Z_TEXT[1]);
        assert!(error(&window, TEXT.len()).contains("window size"));

        assert_eq!(Z_DICT[1] & FLAG_PRESET_DICTIONARY, FLAG_PRESET_DICTIONARY);
        assert!(error(Z_DICT, TEXT.len()).contains("preset dictionary"));
    }

    #[test]
    fn rejects_bad_checksum() {
        for index in Z_TEXT.len() - 4..Z_TEXT.len() {
            let mut stream = Z_TEXT.to_vec();
            stream[index] ^= 0x10;
            assert!(error(&stream, TEXT.len()).contains("Adler-32 mismatch"));
        }
    }

    #[test]
    fn rejects_every_truncation() {
        for stream in [Z_TEXT, Z_STORED, Z_EMPTY] {
            let len = if stream == Z_EMPTY { 0 } else { TEXT.len() };
            for cut in 0..stream.len() {
                assert!(decode(&stream[..cut], len).is_err(), "cut at {cut}");
            }
        }
    }

    #[test]
    fn rejects_output_size_mismatch() {
        let longer = error(Z_TEXT, TEXT.len() - 1);
        assert!(longer.contains("size limit"), "{longer}");
        let shorter = error(Z_TEXT, TEXT.len() + 1);
        assert!(
            shorter.contains("holds 108 bytes, expected 109"),
            "{shorter}"
        );
        assert!(decode(Z_TEXT, 0).is_err());
        assert!(decode(Z_EMPTY, 1).is_err());
        assert!(decode(Z_BIG, 199_999).is_err());
    }

    #[test]
    fn survives_single_byte_corruption() {
        for index in 0..Z_TEXT.len() {
            for flip in [0x01u8, 0x80, 0xFF] {
                let mut stream = Z_TEXT.to_vec();
                stream[index] ^= flip;
                // FLEVEL and the padding bits of the last deflate byte carry
                // no data, so a flip there may still decode.
                if let Ok(out) = decode(&stream, TEXT.len()) {
                    assert_eq!(out, TEXT, "undetected corruption at {index}");
                }
            }
        }
    }
