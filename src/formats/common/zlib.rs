// zlib stream decoding (RFC 1950). Whether this is used depends on the
// enabled format features.
#![allow(dead_code)]

use crate::compat::format;
use crate::error::{Error, Result};

use super::inflate::inflate;

const METHOD_DEFLATE: u8 = 8;
const MAX_WINDOW_BITS: u8 = 7;
const FLAG_PRESET_DICTIONARY: u8 = 1 << 5;
const HEADER_LEN: usize = 2;
const TRAILER_LEN: usize = 4;

const ADLER_MODULUS: u32 = 65521;
// Both sums start below the modulus; over a run of n bytes the second grows
// by at most n * 65520 + 255 * n * (n + 1) / 2, which for n = 4096 stays
// under 2^32, so the reduction can wait until the end of each run.
const ADLER_RUN: usize = 4096;

fn malformed(what: impl core::fmt::Display) -> Error {
    Error::decompression(format!("zlib: {what}"))
}

pub(crate) fn adler32(data: &[u8]) -> u32 {
    let mut low: u32 = 1;
    let mut high: u32 = 0;
    for run in data.chunks(ADLER_RUN) {
        for &byte in run {
            low += u32::from(byte);
            high += low;
        }
        low %= ADLER_MODULUS;
        high %= ADLER_MODULUS;
    }
    (high << 16) | low
}

// Decodes a stream whose output must fill `out` exactly. Bytes after the
// checksum are ignored.
pub(crate) fn zlib_decode_exact(stream: &[u8], out: &mut [u8]) -> Result<()> {
    let (&cmf, &flags) = match stream {
        [cmf, flags, ..] => (cmf, flags),
        _ => return Err(malformed("truncated header")),
    };
    if cmf & 0x0F != METHOD_DEFLATE {
        return Err(malformed(format_args!(
            "unsupported compression method {}",
            cmf & 0x0F
        )));
    }
    if cmf >> 4 > MAX_WINDOW_BITS {
        return Err(malformed("window size above 32 KiB"));
    }
    if ((u16::from(cmf) << 8) | u16::from(flags)) % 31 != 0 {
        return Err(malformed("header check bits do not match"));
    }
    if flags & FLAG_PRESET_DICTIONARY != 0 {
        return Err(malformed("preset dictionary is not supported"));
    }

    let body = stream.get(HEADER_LEN..).unwrap_or_default();
    let expected = out.len() as u64;
    let inflated = inflate(body, expected, expected)?;
    if inflated.data.len() != out.len() {
        return Err(malformed(format_args!(
            "stream holds {} bytes, expected {}",
            inflated.data.len(),
            out.len()
        )));
    }

    let trailer = body
        .get(inflated.consumed..)
        .and_then(|rest| rest.first_chunk::<TRAILER_LEN>())
        .ok_or_else(|| malformed("truncated checksum"))?;
    let stored = u32::from_be_bytes(*trailer);
    let computed = adler32(&inflated.data);
    if stored != computed {
        return Err(malformed(format_args!(
            "Adler-32 mismatch: expected {stored:08x}, computed {computed:08x}"
        )));
    }

    out.copy_from_slice(&inflated.data);
    Ok(())
}

