        let lengths = [(1, 0), (18, 127), (18, 106), (1, 0), (2, 0)];
        fails(
            &dynamic_header(257, 1, &lengths).bits(0, 32).done(),
            "incomplete",
        );

        // Over-subscribed distance set.
        let lengths = [(1, 0), (18, 127), (18, 106), (1, 0), (1, 0), (1, 0), (1, 0)];
        fails(
            &dynamic_header(257, 3, &lengths).bits(0, 32).done(),
            "over-subscribed",
        );

        // HLIT declaring 287 literal/length codes.
        let mut w = BitWriter::new();
        w.bits(1, 1).bits(2, 2).bits(30, 5).bits(0, 5).bits(0, 4);
        w.bits(0, 64);
        fails(&w.done(), "too many literal/length");

