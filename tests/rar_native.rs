#[test]
fn rar29_lz_and_a_solid_group() {
    let archive = rar4_archive(29, &[member("v1.bin", RAR29_V1, b"abcabc")]);
    assert_clean(&archive, "v1.rar", &[("v1.bin", b"abcabc")]);

    let group = |first: &'static [u8]| {
        rar4_archive(
            29,
            &[
                member("m1.txt", first, SOLID_1),
                solid("m2.txt", RAR29_V5_M2, SOLID_2),
                solid("m3.txt", &[0xd5], b""),
                solid("m4.txt", RAR29_V5_M4, SOLID_4),
            ],
        )
    };
    assert_clean(
        &group(RAR29_V5_M1),
        "v5.rar",
        &[
            ("m1.txt", SOLID_1),
            ("m2.txt", SOLID_2),
            ("m3.txt", b""),
            ("m4.txt", SOLID_4),
        ],
    );

    // A first member that cannot be decoded takes the group with it; the
    // empty member is still yielded (docs/USAGE.md).
    let outcome = read(&group(RAR29_E3), "v5.rar");
    assert!(!outcome.root_failure);
    assert_entries(&outcome, "v5.rar", &[("m3.txt", b"")]);
    assert_eq!(outcome.diagnostics.len(), 1, "{:?}", outcome.diagnostics);
}

