//! Black-box regression suite for the RAR reader, through the public API.
//!
//! Every fixture is bytes printed in the specifications under `docs/rar/`;
//! each constant names its document and vector. Whole archives are embedded
//! as printed. Where a document prints only the packed bytes of a member,
//! `rar4_archive` and `rar5_archive` put the minimal container around them
//! that the document says its tools were shown (`rar4-container.md` 18.1 A1,
//! `rar5-container.md` 15.1 C1).
#![cfg(feature = "full")]

use std::io::Write;

use unretro::{ContainerFormat, EntryType, Loader, TraversalDiagnosticCode, VisitAction};

type Listing = Vec<(String, Vec<u8>)>;

struct Outcome {
    entries: Listing,
    diagnostics: Vec<String>,
    root_failure: bool,
}

/// Leaves at any depth, sorted by path, relative to the root name.
fn read(data: &[u8], name: &str) -> Outcome {
    let mut entries = Listing::new();
    let prefix = format!("{name}/");
    let result =
        Loader::from_bytes(data.to_vec(), name).visit_with_report(EntryType::Leaves, |entry| {
            let path = entry.path.strip_prefix(&prefix).unwrap_or(entry.path);
            entries.push((path.to_string(), entry.data.to_vec()));
            Ok(VisitAction::Continue)
        });
    entries.sort();
    match result {
        Ok(report) => {
            for diagnostic in &report.diagnostics {
                assert!(
                    diagnostic.is_root_failure()
                        || diagnostic.code == TraversalDiagnosticCode::ContainerEntriesSkipped,
                    "unexpected diagnostic {:?}",
                    diagnostic
                );
            }
            Outcome {
                root_failure: report.has_root_failures(),
                diagnostics: report
                    .diagnostics
                    .iter()
                    .map(|d| d.message.clone())
                    .collect(),
                entries,
            }
        }
        Err(error) => Outcome {
            entries,
            diagnostics: vec![error.to_string()],
            root_failure: true,
        },
    }
}

/// The archive is read without any diagnostic and yields exactly `expected`.
#[track_caller]
fn assert_clean(data: &[u8], name: &str, expected: &[(&str, &[u8])]) {
    let outcome = read(data, name);
    assert!(
        outcome.diagnostics.is_empty(),
        "{name}: {:?}",
        outcome.diagnostics
    );
    assert_entries(&outcome, name, expected);
}

#[track_caller]
fn assert_entries(outcome: &Outcome, name: &str, expected: &[(&str, &[u8])]) {
    let mut expected: Vec<(&str, &[u8])> = expected.to_vec();
    expected.sort();
    let got: Vec<&str> = outcome
        .entries
        .iter()
        .map(|(path, _)| path.as_str())
        .collect();
    let want: Vec<&str> = expected.iter().map(|(path, _)| *path).collect();
    assert_eq!(
        got, want,
        "entries of {name}; diagnostics {:?}",
        outcome.diagnostics
    );
    for ((path, data), (_, want)) in outcome.entries.iter().zip(&expected) {
        assert!(data == want, "content of {path} in {name}: {data:02x?}");
    }
}

/// The archive opens, yields exactly `expected`, and reports one
/// `ContainerEntriesSkipped` diagnostic containing every string of `messages`.
#[track_caller]
fn assert_skipped(data: &[u8], name: &str, expected: &[(&str, &[u8])], messages: &[&str]) {
    let outcome = read(data, name);
    assert!(!outcome.root_failure, "{name}: {:?}", outcome.diagnostics);
    assert_entries(&outcome, name, expected);
    assert_eq!(
        outcome.diagnostics.len(),
        1,
        "{name}: {:?}",
        outcome.diagnostics
    );
    for message in messages {
        assert!(
            outcome.diagnostics[0].contains(message),
            "{name}: {:?} lacks {message:?}",
            outcome.diagnostics[0]
        );
    }
}

fn crc32(data: &[u8]) -> u32 {
    let mut crc = !0u32;
    for &byte in data {
        crc ^= u32::from(byte);
        for _ in 0..8 {
            crc = (crc >> 1) ^ (0xEDB8_8320 & (!(crc & 1)).wrapping_add(1));
        }
    }
    !crc
}

/// One member of a crafted archive: name, packed bytes, expected contents,
/// and whether it continues the solid group of the member before it.
struct Member<'a> {
    name: &'a str,
    packed: &'a [u8],
    contents: &'a [u8],
    solid: bool,
}

fn member<'a>(name: &'a str, packed: &'a [u8], contents: &'a [u8]) -> Member<'a> {
    Member {
        name,
        packed,
        contents,
        solid: false,
    }
}

fn solid<'a>(name: &'a str, packed: &'a [u8], contents: &'a [u8]) -> Member<'a> {
    Member {
        name,
        packed,
        contents,
        solid: true,
    }
}

/// A RAR4-format archive laid out like vector A1 of `rar4-container.md`:
/// archive header, then one file header (method 0x33) and data per member.
fn rar4_archive(unpack_version: u8, members: &[Member<'_>]) -> Vec<u8> {
    let mut out = b"Rar!\x1a\x07\x00".to_vec();
    let block = |out: &mut Vec<u8>, body: &[u8]| {
        out.extend_from_slice(&(crc32(body) as u16).to_le_bytes());
        out.extend_from_slice(body);
    };
    block(&mut out, &[0x73, 0, 0, 13, 0, 0, 0, 0, 0, 0, 0]);
    for m in members {
        let flags: u16 = if m.solid { 0x8010 } else { 0x8000 };
        let mut head = vec![0x74];
        head.extend_from_slice(&flags.to_le_bytes());
        head.extend_from_slice(&(32 + m.name.len() as u16).to_le_bytes());
        head.extend_from_slice(&(m.packed.len() as u32).to_le_bytes());
        head.extend_from_slice(&(m.contents.len() as u32).to_le_bytes());
        head.push(0);
        head.extend_from_slice(&crc32(m.contents).to_le_bytes());
        head.extend_from_slice(&0x2A43_20A3u32.to_le_bytes());
        head.push(unpack_version);
        head.push(0x33);
        head.extend_from_slice(&(m.name.len() as u16).to_le_bytes());
        head.extend_from_slice(&0x20u32.to_le_bytes());
        head.extend_from_slice(m.name.as_bytes());
        block(&mut out, &head);
        out.extend_from_slice(m.packed);
    }
    out
}

/// A RAR 5 archive laid out like vector C1 of `rar5-container.md`: main
/// header, one file header and data area per member, end of archive.
/// `algorithm` is the version field of the compression information; the
/// method is 3 and the dictionary 128 KiB, as `rar5-compression.md` 13 says.
fn rar5_archive(algorithm: u8, members: &[Member<'_>]) -> Vec<u8> {
    let mut out = b"Rar!\x1a\x07\x01\x00".to_vec();
    let block = |out: &mut Vec<u8>, body: &[u8]| {
        assert!(body.len() < 0x80);
        let mut sized = vec![body.len() as u8];
        sized.extend_from_slice(body);
        out.extend_from_slice(&crc32(&sized).to_le_bytes());
        out.extend_from_slice(&sized);
    };
    block(&mut out, &[1, 0, 0]);
    for m in members {
        assert!(m.packed.len() < 0x80 && m.contents.len() < 0x80 && m.name.len() < 0x80);
        let mut head = vec![2, 2, m.packed.len() as u8, 4, m.contents.len() as u8];
        head.extend_from_slice(&[0xa4, 0x83, 0x02]);
        head.extend_from_slice(&crc32(m.contents).to_le_bytes());
        // Version in bits 0..5, solid in bit 6, method 3 in bits 7..9.
        head.extend_from_slice(&[0x80 | algorithm | if m.solid { 0x40 } else { 0 }, 0x03]);
        head.extend_from_slice(&[1, m.name.len() as u8]);
        head.extend_from_slice(m.name.as_bytes());
        block(&mut out, &head);
        out.extend_from_slice(m.packed);
    }
    block(&mut out, &[5, 0, 0]);
    out
}

/// A stored ZIP holding `files`: the parent container a volume set is found in.
fn zip_of(files: &[(&str, &[u8])]) -> Vec<u8> {
    let mut out = Vec::new();
    let mut writer = zip::ZipWriter::new(std::io::Cursor::new(&mut out));
    let options =
        zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Stored);
    for (name, data) in files {
        writer.start_file(*name, options).unwrap();
        writer.write_all(data).unwrap();
    }
    writer.finish().unwrap();
    out
}

fn changed(data: &[u8], edits: &[(usize, u8)]) -> Vec<u8> {
    let mut data = data.to_vec();
    for &(offset, value) in edits {
        data[offset] = value;
    }
    data
}

