fn corrupt_streams_are_skipped() {
    let cases: [(u8, &[u8], usize); 6] = [
        (20, RAR20_E2, 1),
        (29, RAR29_E3, 4),
        (29, RAR29_E8, 10),
        // rar29-lz.md E9: the first 12 bytes of E8.
        (29, &RAR29_E8[..12], 6),
        // rar29-lz.md E10: no packed bytes for a member of 6 bytes.
        (29, &[], 6),
        // A PPMd stream cut short.
        (29, &PPMD_V2[..9], 24),
    ];
    for (version, packed, size) in cases {
        let contents = vec![b'x'; size];
        let archive = rar4_archive(
            version,
            &[
                member("bad.bin", packed, &contents),
                member(
                    "good.bin",
                    if version == 20 { RAR20_V1 } else { RAR29_V1 },
                    b"abcabc",
                ),
            ],
        );
        assert_skipped(
            &archive,
            "bad.rar",
            &[("good.bin", b"abcabc")],
            &["'bad.bin'"],
        );
    }

    let archive = rar5_archive(
        0,
        &[
            member("bad.bin", RAR5_CE1, b"abcabc"),
            member("good.bin", RAR5_V9A, &[0; 20]),
        ],
    );
    // good.bin carries a wrong CRC-32 here, so both members are skipped.
    assert_skipped(&archive, "bad.rar", &[], &["'bad.bin'", "'good.bin'"]);

    // Every single-byte truncation and every flipped byte of two small
    // archives is read without a panic.
    for archive in [RAR5_G1, RAR15_SOLID_PAIR] {
        for cut in 0..archive.len() {
            read(&archive[..cut], "cut.rar");
        }
        for offset in 0..archive.len() {
            read(&changed(archive, &[(offset, !archive[offset])]), "flip.rar");
        }
    }
}
